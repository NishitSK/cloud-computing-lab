from datetime import datetime, timezone
from wsgiref.simple_server import make_server

PAGE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>App Engine Web App | Nishit S K</title>
<style>
  body { margin: 0; font-family: "Segoe UI", Arial, sans-serif; color: #0b1f3a; background: #ffffff; }
  header { background: #0b1f3a; color: #ffffff; padding: 32px 24px; }
  header h1 { margin: 0; font-size: 1.6rem; }
  main { max-width: 720px; margin: 0 auto; padding: 32px 24px; }
  td { padding: 8px 24px 8px 0; border-bottom: 1px solid #e3e8f0; }
  td:first-child { color: #4a5a73; }
</style>
</head>
<body>
<header>
  <h1>Web Application on Google App Engine</h1>
</header>
<main>
  <p>This page is generated by a Python WSGI application.</p>
  <table>
    <tr><td>Server time</td><td>__TIME__</td></tr>
    <tr><td>Name</td><td>Nishit S K</td></tr>
    <tr><td>USN</td><td>4SF23CS130</td></tr>
  </table>
</main>
</body>
</html>
"""


def app(environ, start_response):
    if environ.get("PATH_INFO", "/") != "/":
        start_response("404 Not Found", [("Content-Type", "text/plain; charset=utf-8")])
        return [b"Not found"]

    now = datetime.now(timezone.utc).strftime("%d %b %Y, %H:%M:%S UTC")
    body = PAGE.replace("__TIME__", now).encode("utf-8")

    start_response("200 OK", [
        ("Content-Type", "text/html; charset=utf-8"),
        ("Content-Length", str(len(body))),
    ])
    return [body]


if __name__ == "__main__":
    # Local run only. On App Engine the runtime serves `app` itself.
    with make_server("", 8080, app) as server:
        print("Serving on http://localhost:8080")
        server.serve_forever()
